import { test } from "node:test";
import assert from "node:assert/strict";
import { isSpace, isSpaceAt } from "../src/is_space.ts";

test("chars::isSpace", (): void => {
  assert.ok(isSpace(32));
  assert.ok(isSpace(9));
  assert.ok(isSpace(10));
  assert.ok(isSpace(11));
  assert.ok(isSpace(12));
  assert.ok(isSpace(13));
  assert.ok(isSpace(133));
  assert.ok(isSpace(160));
  assert.ok(isSpace(5760));
  assert.ok(isSpace(8192));
  assert.ok(isSpace(8193));
  assert.ok(isSpace(8194));
  assert.ok(isSpace(8195));
  assert.ok(isSpace(8196));
  assert.ok(isSpace(8197));
  assert.ok(isSpace(8198));
  assert.ok(isSpace(8199));
  assert.ok(isSpace(8200));
  assert.ok(isSpace(8201));
  assert.ok(isSpace(8202));
  assert.ok(isSpace(8232));
  assert.ok(isSpace(8233));
  assert.ok(isSpace(8239));
  assert.ok(isSpace(8287));
  assert.ok(isSpace(12288));
  assert.ok(!isSpace(0));
  assert.ok(!isSpace(127));
  assert.ok(!isSpace(128));
  assert.ok(!isSpace(255));
  assert.ok(!isSpace(256));
  assert.ok(!isSpace(-1));
  assert.ok(!isSpace(-128));
  assert.ok(!isSpace(-255));
  assert.ok(!isSpace(-256));
  assert.ok(!isSpace(Infinity));
  assert.ok(!isSpace(-Infinity));
  assert.ok(!isSpace(NaN));
  assert.ok(!isSpace(0.1));
  assert.ok(!isSpace(-0.1));
  assert.ok(!isSpace(0.9));
  assert.ok(!isSpace(-0.9));
  assert.ok(!isSpace(1.1));
  assert.ok(!isSpace(-1.1));
  assert.ok(!isSpace(1.9));
  assert.ok(!isSpace(-1.9));
  assert.ok(!isSpace(1.0));
  assert.ok(!isSpace(-1.0));
  assert.ok(!isSpace(0.0));
  assert.ok(!isSpace(-0.0));
  assert.ok(!isSpace(0.0000000000001));
  assert.ok(!isSpace(-0.0000000000001));
  assert.ok(!isSpace(0.0000000000009));
  assert.ok(!isSpace(-0.0000000000009));
  assert.ok(!isSpace(0.0000000000011));
  assert.ok(!isSpace(-0.0000000000011));
});

test("chars::isSpaceAt", (): void => {
  const str = "Holy 💩\n\t\f\r";
  assert.ok(!isSpaceAt(str, 0));
  assert.ok(!isSpaceAt(str, 1));
  assert.ok(!isSpaceAt(str, 2));
  assert.ok(!isSpaceAt(str, 3));
  assert.ok(isSpaceAt(str, 4));
  assert.ok(!isSpaceAt(str, 5));
  assert.ok(isSpaceAt(str, 7));
  assert.ok(isSpaceAt(str, 8));
  assert.ok(isSpaceAt(str, 9));
  assert.ok(isSpaceAt(str, 10));
});
